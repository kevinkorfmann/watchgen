class TestTwoLocusKernel:
    def test_matches_matrix_exponential_of_source_generator(self):
        duration, coal_rate, rho = 1.3, 0.7, 0.2
        generator = np.array(
            [[-rho, rho, 0.0], [coal_rate, -2 * coal_rate, coal_rate], [0, 0, 0]]
        )
        np.testing.assert_allclose(
            two_locus_kernel(duration, coal_rate, rho),
            expm(duration * generator),
            rtol=1e-13,
            atol=1e-13,
        )

    def test_stochastic_and_absorbing(self):
        kernel = two_locus_kernel(2.0, 1.0, 0.1)
        assert np.all(kernel >= 0)
        np.testing.assert_allclose(kernel.sum(axis=1), 1.0)
        np.testing.assert_array_equal(kernel[2], [0, 0, 1])

    def test_no_recombination_never_leaves_linked_state(self):
        np.testing.assert_array_equal(two_locus_kernel(10, 1, 0)[0], [1, 0, 0])


class TestDiscretizedTransition:
    def test_rows_are_probability_distributions(self):
        P = constant_csc_transition_matrix(BREAKS, 1.0, 0.1)
        assert np.all(P >= 0)
        np.testing.assert_allclose(P.sum(axis=1), 1.0)

    def test_zero_recombination_is_identity(self):
        np.testing.assert_allclose(
            constant_csc_transition_matrix(BREAKS, 1.0, 0.0), np.eye(len(BREAKS) - 1)
        )

    def test_transition_does_not_depend_on_undistinguished_sample_count(self):
        # Sample size is absent from the API by design: extra samples affect
        # CSFS emissions, not the distinguished pair's transition process.
        P = constant_csc_transition_matrix(BREAKS, 1.0, 0.1)
        assert P.shape == (4, 4)

    def test_matches_original_cpp_transition_matrix(self):
        # Generated by upstream transition.cpp at commit 6779faec. Production
        # SMC++ mixes in beta=1e-5 uniformly over its five time boundaries;
        # undo that stabilizer because this teaching implementation omits it.
        upstream_regularized = np.array(
            [
                [
                    0.99174529246296617,
                    0.0032468265741395557,
                    0.0035708180737013995,
                    0.0014350628891928771,
                ],
                [
                    0.0026436261133923051,
                    0.979094191031328,
                    0.013027698894885299,
                    0.0052324839603943938,
                ],
                [
                    0.0026436261133923051,
                    0.015019266270524353,
                    0.96997636130338538,
                    0.012358746312697949,
                ],
                [
                    0.0026436261133923051,
                    0.015019266270524353,
                    0.053560572100880742,
                    0.92877453551520261,
                ],
            ]
        )
        beta = 1e-5
        upstream = (upstream_regularized - beta / len(BREAKS)) / (1 - beta)
        np.testing.assert_allclose(
            constant_csc_transition_matrix(BREAKS, 1.0, 0.1),
            upstream,
            rtol=2e-13,
            atol=2e-13,
        )


class TestLikelihood:
    @pytest.fixture
    def model(self):
        emissions = emission_probabilities(BREAKS, 2, 0.02, quadrature_order=8)
        transitions = constant_csc_transition_matrix(BREAKS, 1.0, 0.1)
        initial = pair_interval_probabilities(BREAKS)
        return transitions, emissions, initial

    def test_scaled_forward_matches_brute_force(self, model):
        transitions, emissions, initial = model
        observations = np.array([[0, 0], [1, 0], [0, 1]])
        alpha = initial * emissions[:, 0, 0]
        alpha = (alpha @ transitions) * emissions[:, 1, 0]
        alpha = (alpha @ transitions) * emissions[:, 0, 1]
        expected = np.log(alpha.sum())
        assert forward_log_likelihood(
            observations, transitions, emissions, initial
        ) == pytest.approx(expected)

    def test_missing_observation_has_unit_emission(self, model):
        transitions, emissions, initial = model
        data = np.array([[0, 0], [-1, -1], [1, 0]])
        without_missing = np.array([[0, 0], [1, 0]])
        # A missing site still advances the Markov chain once.
        P2 = transitions @ transitions
        assert forward_log_likelihood(
            data, transitions, emissions, initial
        ) == pytest.approx(
            forward_log_likelihood(without_missing, P2, emissions, initial)
        )

    def test_composite_is_sum_not_independence_claim(self, model):
        transitions, emissions, initial = model
        d1 = np.array([[0, 0], [1, 0]])
        d2 = np.array([[0, 0], [0, 1]])
        expected = sum(
            forward_log_likelihood(d, transitions, emissions, initial) for d in (d1, d2)
        )
        assert composite_log_likelihood(
            [d1, d2], transitions, emissions, initial
        ) == pytest.approx(expected)


class TestCleanSplitSupport:
    def test_no_cross_population_coalescence_before_split(self):
        for t in [0, 0.2, 1.0]:
            assert cross_population_survival(t, 1.0, lambda _: 2.0) == 1.0

    def test_ancestral_exponential_tail(self):
        split = 1.0
        rate = 0.5
        for t in [1.0, 1.5, 3.0]:
            expected = np.exp(-rate * max(t - split, 0))
            assert cross_population_survival(t, split, lambda _: rate) == pytest.approx(
                expected
            )
