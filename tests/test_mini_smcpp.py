class TestCoalescentUnits:
    def test_pair_mean_is_2N_generations(self):
        assert expected_first_coalescence(2, 10_000) == 20_000

    def test_first_event_rate_for_many_lineages(self):
        assert expected_first_coalescence(20, 10_000) == pytest.approx(20_000 / 190)

